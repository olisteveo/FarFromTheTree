export const WIDE = { I: 0.35, ".": 0.3, "'": 0.3, "!": 0.35, 1: 0.65 };


/** A word() drawing its wobble from the caller's random source, so each sheet stays reproducible. */
export const wordWith = (between) => function word(text, x, y, w, h, { jitter = 0, slant = 0, gap = 0.22, bounce = 0 } = {}) {
  const chars = [...text];
  const units = chars.reduce((n, c) => n + (c === " " ? 0.55 : (WIDE[c] ?? 1)) + gap, -gap);
  const cw = Math.min(w / units, h * 1.15);
  const lineW = units * cw;
  let cx = x + (w - lineW) / 2;
  const paths = [];
  for (const c of chars) {
    if (c === " ") { cx += (0.55 + gap) * cw; continue; }
    const wide = WIDE[c] ?? 1, dy = bounce ? between(-bounce, bounce) * h : 0;
    for (const line of LETTERS[c] ?? []) {
      const pts = line.map(([px, py]) => {
        const lx = cx + px * wide * cw + between(-jitter, jitter) * cw;
        const ly = y + dy + py * h + between(-jitter, jitter) * h;
        return [lx + (y + h - ly) * slant, ly];
      });
      paths.push("M" + pts.map((p) => p[0].toFixed(1) + " " + p[1].toFixed(1)).join("L"));
    }
    cx += (wide + gap) * cw;
  }
  return paths.join("");
};
